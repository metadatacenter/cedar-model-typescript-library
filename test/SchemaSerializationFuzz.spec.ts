import {
  CedarBuilders,
  CedarReaders,
  CedarWriters,
  BiboStatus,
  SchemaVersion,
  NumberType,
  TemporalType,
  TemporalGranularity,
  Template,
  TemplateElement,
  TemplateField,
  Iri,
  ChildDeploymentInfoBuilder,
  ChildDeploymentInfoAlwaysMultipleBuilder,
  AbstractDynamicChildDeploymentInfoBuilder,
} from '../src';
import { Command, commands, checkHistory, historySeeds } from './support/seeded-history';
import type { JsonNode } from '../src/org/metadatacenter/model/cedar/types/basic-types/JsonNode';

interface Node {
  key: string;
  name: string;
  command: Command;
  children: Node[] | null;
  depth: number;
}
const names = ['on', 'null', '007', 'a: b # c', 'é Δ 😀', '"quoted"'];
function field(node: Node): TemplateField {
  const c = node.command;
  const builder = (() => {
    switch (c.op) {
      case 1:
        return CedarBuilders.textFieldBuilder()
          .withMinLength(0)
          .withMaxLength(100)
          .withDefaultValue(names[c.b % names.length]);
      case 2:
        return CedarBuilders.textAreaBuilder().withDefaultValue('first\nsecond\n');
      case 3:
        return CedarBuilders.numericFieldBuilder()
          .withNumberType(NumberType.forValue('xsd:int'))
          .withMinValue(0)
          .withMaxValue(100)
          .withDefaultValue(c.b % 100);
      case 4:
        return CedarBuilders.emailFieldBuilder().withDefaultValue('person@example.org');
      case 5:
        return CedarBuilders.linkFieldBuilder().withDefaultValue(new Iri('https://example.org/link'));
      case 6:
        return CedarBuilders.temporalFieldBuilder()
          .withTemporalType(TemporalType.forValue('xsd:date'))
          .withTemporalGranularity(TemporalGranularity.forValue('day'))
          .withDefaultValue('2026-10-09');
      case 7:
        return CedarBuilders.checkboxFieldBuilder().addCheckboxOption('on', true).addCheckboxOption('null', false);
      case 8:
        return CedarBuilders.radioFieldBuilder().addRadioOption('Alpha', true).addRadioOption('Beta', false);
      default:
        return CedarBuilders.textFieldBuilder();
    }
  })();
  return builder
    .withAtId(`https://example.org/field/${node.key}`)
    .withSchemaName(node.name)
    .withDescription(`${node.name} field schema generated by the CEDAR Artifact Library`)
    .withSchemaDescription(`Help ${node.name}`)
    .build();
}
function build(node: Node, root = false): Template | TemplateElement {
  const builder = (root ? CedarBuilders.templateBuilder() : CedarBuilders.templateElementBuilder())
    .withAtId(`https://example.org/${root ? 'template' : 'element'}/${node.key}`)
    .withSchemaName(node.name)
    .withDescription(`${node.name} ${root ? 'template' : 'element'} schema generated by the CEDAR Artifact Library`)
    .withSchemaDescription(`Help ${node.name}`)
    .withSchemaVersion(SchemaVersion.CURRENT)
    .withStatus(BiboStatus.DRAFT);
  for (const child of node.children ?? []) {
    if (child.children !== null) {
      const element = build(child) as TemplateElement;
      const deployment = element
        .createDeploymentBuilder(child.key)
        .withIri(`https://example.org/property/${child.key}`)
        .withLabel(child.name)
        .withDescription(`Help ${child.name}`)
        .withMultiInstance(child.command.c % 2 === 0)
        .withMinItems(child.command.c % 2 === 0 ? 1 : null)
        .withMaxItems(child.command.c % 2 === 0 ? 3 : null)
        .build();
      builder.addChild(element, deployment);
    } else {
      const value = field(child);
      const deployment = value.createDeploymentBuilder(child.key).withLabel(child.name).withDescription(`Help ${child.name}`);
      if (deployment instanceof AbstractDynamicChildDeploymentInfoBuilder) deployment.withIri(`https://example.org/property/${child.key}`);
      if (deployment instanceof ChildDeploymentInfoBuilder) {
        const multiple = child.command.c % 2 === 0;
        deployment
          .withMultiInstance(multiple)
          .withMinItems(multiple ? 1 : null)
          .withMaxItems(multiple ? 4 : null);
      } else if (deployment instanceof ChildDeploymentInfoAlwaysMultipleBuilder) deployment.withMinItems(0).withMaxItems(2);
      builder.addChild(value, deployment.build());
    }
  }
  return builder.build();
}
function verifyNames(json: JsonNode, source: Node): void {
  expect(json['schema:name']).toBe(source.name);
  expect(json['schema:description']).toBe(`Help ${source.name}`);
  if (!source.children) return;
  expect((json['_ui'] as JsonNode)['order']).toEqual(source.children.map((child) => child.key));
  const properties = json['properties'] as Record<string, JsonNode>;
  for (const child of source.children) {
    const held = properties[child.key];
    verifyNames((held['items'] ?? held) as JsonNode, child);
  }
}
function replay(history: Command[]): void {
  const root: Node = { key: 'root', name: 'Generated', command: { op: 0, a: 0, b: 0, c: 0 }, children: [], depth: 0 };
  const containers = [root];
  history.forEach((command, index) => {
    const parent = containers[command.a % containers.length];
    const child: Node = {
      key: `key${index}`,
      name: names[command.b % names.length],
      command,
      children: command.op === 0 && parent.depth < 4 ? [] : null,
      depth: parent.depth + 1,
    };
    parent.children!.push(child);
    if (child.children) containers.push(child);
  });
  const snapshot = JSON.stringify(root);
  const model = build(root, true) as Template;
  const writer = CedarWriters.json().getStrict().getTemplateWriter();
  const yamlWriter = CedarWriters.yaml().getStrict().getTemplateWriter();
  const json = writer.getAsJsonNode(model);
  verifyNames(json, root);
  const viaJson = CedarReaders.json().getStrict().getTemplateReader().readFromString(JSON.stringify(json)).template;
  expect(writer.getAsJsonNode(viaJson)).toEqual(json);
  const yaml = yamlWriter.getAsYamlString(model);
  const viaYaml = CedarReaders.yaml().getStrict().getTemplateReader().readFromString(yaml).template;
  expect(writer.getAsJsonNode(viaYaml)).toEqual(json);
  expect(yamlWriter.getAsYamlString(viaYaml)).toBe(yaml);
  expect(JSON.stringify(root)).toBe(snapshot);
}

describe('seeded nested schema serialization', () => {
  test.each(historySeeds(150))('seed %i', (seed) => checkHistory(seed, commands(seed, 20, 10), replay));
});
