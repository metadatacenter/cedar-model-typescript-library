// Compile the canonical Draft-04 meta-schemas ahead of time. Browsers never evaluate source code.
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs');
const { resolve } = require('node:path');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const Ajv = require('ajv-draft-04');
const standalone = require('ajv/dist/standalone').default;
const { _ } = require('ajv/dist/compile/codegen');
const root = resolve(__dirname, '..');
const inputs = resolve(root, 'itest/resources/meta-schemas');
const output = resolve(root, 'src/org/metadatacenter/model/cedar/validation/generated');
const files = {
  template: 'template-meta-schema.json',
  element: 'element-meta-schema.json',
  literal: 'literal-field-meta-schema.json',
  iri: 'iri-field-meta-schema.json',
  staticField: 'static-field-meta-schema.json',
  multiple: 'multi-instance-field-meta-schema.json',
};
const sync = process.argv.indexOf('--sync');
if (sync !== -1) {
  const java = resolve(process.argv[sync + 1]);
  mkdirSync(inputs, { recursive: true });
  const hashes = {};
  for (const file of Object.values(files)) {
    const bytes = readFileSync(resolve(java, 'src/main/resources', file));
    writeFileSync(resolve(inputs, file), bytes);
    hashes[file] = createHash('sha256').update(bytes).digest('hex');
  }
  writeFileSync(
    resolve(inputs, 'lock.json'),
    JSON.stringify(
      {
        repository: 'cedar-model-validation-library',
        revision: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: java, encoding: 'utf8' }).trim(),
        modified: Boolean(
          execFileSync('git', ['diff', 'HEAD', '--', ...Object.values(files).map((file) => 'src/main/resources/' + file)], {
            cwd: java,
            encoding: 'utf8',
          }).trim(),
        ),
        hashes,
      },
      null,
      2,
    ) + '\n',
  );
}
const lock = JSON.parse(readFileSync(resolve(inputs, 'lock.json'), 'utf8'));
const ajv = new Ajv({
  strict: false,
  strictNumbers: false,
  allErrors: true,
  inlineRefs: false,
  code: { source: true, formats: _`require("../SchemaFormats").schemaFormats` },
});
// Standalone output obtains the implementations from SchemaFormats. These functions are never run here.
for (const name of ['uri', 'date-time']) ajv.addFormat(name, { type: 'string', validate: () => true });
const definitions = {};
for (const [name, file] of Object.entries(files)) {
  const bytes = readFileSync(resolve(inputs, file));
  if (createHash('sha256').update(bytes).digest('hex') !== lock.hashes[file]) throw new Error(`Schema lock mismatch: ${file}`);
  const { definitions: common, ...schema } = JSON.parse(bytes);
  // Java resources repeat the same named definitions. Share their compiled functions, but refuse
  // drift rather than silently choosing one resource's definition over another's.
  for (const [key, value] of Object.entries(common)) {
    if (definitions[key] && JSON.stringify(definitions[key]) !== JSON.stringify(value))
      throw new Error(`Conflicting canonical definition: ${key}`);
    definitions[key] = value;
  }
  definitions['artifact_' + name] = schema;
}
// Annotations do not affect a verdict. Remove them only at schema positions (never from enum
// values or the names under `properties`), then share identical standalone/nested definitions.
function assertions(schema) {
  if (!schema || typeof schema !== 'object' || Array.isArray(schema)) return schema;
  const result = { ...schema };
  for (const key of ['description', 'title', 'default', 'examples', '$comment']) delete result[key];
  for (const key of ['properties', 'patternProperties', 'definitions', 'dependencies'])
    if (result[key]) result[key] = Object.fromEntries(Object.entries(result[key]).map(([name, child]) => [name, assertions(child)]));
  for (const key of ['items', 'additionalItems', 'additionalProperties', 'not'])
    if (result[key] && !Array.isArray(result[key])) result[key] = assertions(result[key]);
  for (const key of ['allOf', 'anyOf', 'oneOf', 'items']) if (Array.isArray(result[key])) result[key] = result[key].map(assertions);
  return result;
}
const canonical = (value) =>
  JSON.stringify(value, (_key, item) =>
    item && typeof item === 'object' && !Array.isArray(item)
      ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a.localeCompare(b)))
      : item,
  );
const equivalent = new Map();
for (const [key, value] of Object.entries(definitions)) {
  const clean = assertions(value),
    signature = canonical(clean),
    prior = equivalent.get(signature);
  definitions[key] = prior ? { $ref: '#/definitions/' + prior } : clean;
  if (!prior) equivalent.set(signature, key);
}
ajv.addSchema({ definitions }, 'cedar');
const code =
  '// Generated by scripts/compile-artifact-schemas.cjs; do not edit.\n' +
  standalone(ajv, {
    ...Object.fromEntries(Object.keys(files).map((name) => [name, 'cedar#/definitions/artifact_' + name])),
    attributeField: 'cedar#/definitions/attributeValueTemplateField',
    multipleChild: 'cedar#/definitions/multiInstanceTemplateFieldOrElement',
  }) +
  '\nexports.schemaDigests = ' +
  JSON.stringify(lock.hashes) +
  ';\n';
const path = resolve(output, 'artifact-schemas.js');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== code) throw new Error('Compiled meta-schemas are stale; run npm run schemas:compile.');
} else {
  mkdirSync(output, { recursive: true });
  writeFileSync(path, code);
}

// Compile the small shared constraint value separately for picker/policy consumers.
const linksCode =
  '// Generated by scripts/compile-artifact-schemas.cjs; do not edit.\n' +
  standalone(ajv, { constraintLinks: 'cedar#/definitions/valueConstraintsLinksFieldContent' });
const linksPath = resolve(output, 'constraint-links.js');
if (process.argv.includes('--check')) {
  if (readFileSync(linksPath, 'utf8') !== linksCode) throw new Error('Compiled constraint links are stale.');
} else writeFileSync(linksPath, linksCode);
